import {test,expect} from '@playwright/test'

test.afterAll(async({request})=>{await request.post('/__synthetic_shutdown')})

test('teacher completes record questions, uploaded transcript review and authored report through real local API',async({page},testInfo)=>{
 const outside:string[]=[],errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',route=>{if(new URL(route.request().url()).hostname!=='127.0.0.1'){outside.push(route.request().url());return route.abort()}return route.continue()})
 await page.goto('/counseling/')
 await page.getByRole('button',{name:'학생부 모의면접',exact:true}).click()
 const root=page.getByRole('region',{name:'학생부 모의면접',exact:true})
 await expect(root).toBeVisible()
 await root.locator('.record-selection input[type=checkbox]').first().check()
 await root.getByLabel('선택한 기재를 학생부 원본과 대조했습니다.').check()
 await root.getByLabel('학생 보충 설명',{exact:true}).fill('직접 관찰표와 평균 계산을 담당했다고 학생이 설명했다.')
 await root.getByRole('button',{name:'근거·보충 설명 저장'}).click()
 await root.getByRole('button',{name:'AI 분석·질문 생성',exact:true}).click()
 await expect(root.getByLabel('Q001 질문',{exact:true})).toBeVisible()
 await root.getByLabel('Q001 검토 상태',{exact:true}).selectOption('accepted')
 await expect(root.getByRole('button',{name:'② 전사본 검토'})).toBeDisabled()
 await root.getByRole('button',{name:'질문 검토 저장'}).click()
 await root.getByRole('button',{name:'② 전사본 검토'}).click()
 await root.getByLabel('전사본 파일',{exact:true}).setInputFiles({name:'합성면접.txt',mimeType:'text/plain',buffer:Buffer.from('면접관: 직접 맡은 일은 무엇인가요?\n학생: 관찰한 값을 표로 정리하고 평균을 계산했습니다.\n면접관: 다시 한다면 무엇을 바꾸겠나요?\n학생: 측정 횟수를 늘려 값의 차이를 확인하겠습니다.')})
 await root.getByRole('button',{name:'AI 전사본 사전 검토',exact:true}).click()
 await expect(root.getByText('AI가 별도 의심 사항을 제시하지 않았습니다. 교사가 화자·문답·내용을 확인하세요.')).toBeVisible()
 for(const id of ['T0001','T0002','T0003','T0004'])await root.getByLabel(id+' 확인 상태',{exact:true}).selectOption('confirmed')
 await root.getByLabel('T0002 검토 내용',{exact:true}).fill('관찰한 값을 표로 정리하고 평균을 계산했습니다. 계산 과정을 직접 확인했습니다.')
 await root.getByRole('button',{name:'전사본 교사 검토 저장'}).click()
 await root.getByRole('button',{name:'③ 종합 보고서'}).click()
 await root.getByRole('button',{name:'AI 종합 보고서 초안 작성',exact:true}).click()
 const summary=root.getByLabel('종합 의견',{exact:true})
 await expect(summary).toBeVisible()
 await summary.fill('교사가 추가한 실제 지도 맥락을 보존합니다.')
 await root.getByLabel('교사 최종 의견',{exact:true}).fill('다음 면접에서 평균을 선택한 이유를 확인한다.')
 await root.getByRole('button',{name:'교사 추가·보완 저장'}).click()
 await root.getByRole('button',{name:'AI 종합 보고서 초안 작성',exact:true}).click()
 await expect(root.getByLabel('보고서 판본',{exact:true}).locator('option')).toHaveCount(2)
 const firstId=await root.getByLabel('보고서 판본',{exact:true}).locator('option').first().getAttribute('value')
 await root.getByLabel('보고서 판본',{exact:true}).selectOption(firstId!)
 await expect(summary).toHaveValue('교사가 추가한 실제 지도 맥락을 보존합니다.')
 await root.getByLabel('학생·전사 근거와 교사 보완 내용을 확인했습니다.').check()
 await root.getByRole('button',{name:'교사 확인 후 보고서 확정'}).click()
 await expect(summary).toBeDisabled()
 for(const name of ['Word 저장','PDF 저장']){
  const pending=page.waitForEvent('download');await root.getByRole('button',{name,exact:true}).click();const result=await pending
  await result.saveAs(testInfo.outputPath(result.suggestedFilename()))
 }
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
 await page.screenshot({path:testInfo.outputPath('interview-report-390.png'),fullPage:true})
 expect(outside).toEqual([]);expect(errors).toEqual([])
})
