import {test,expect} from '@playwright/test'

test.afterAll(async({request})=>{await request.post('/__synthetic_shutdown')})
test('reload restores the active student and cancellation can resume validated source batches',async({page,request},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',dialog=>dialog.accept())
 const health=await(await request.get('/api/health')).json()
 const records=await(await request.get('/api/cases')).json()
 const target=records.cases.find((c:any)=>c.student.student_number==='DEMO-RESUME')
 const started=await request.post('/api/cases/'+target.id+'/analyze',{headers:{'X-Counseling-Token':health.csrf_token},data:{revision:target.revision,session_id:target.current_session_id,model:'synthetic-local',goal:''}})
 expect(started.status()).toBe(202)
 await page.goto('/counseling/')
 await expect(page.getByRole('heading',{name:'DEMO-RESUME 합성 이어하기 학생'})).toBeVisible()
 const status=page.getByRole('region',{name:'분석 작업 상태',exact:true})
 await expect(status.getByText(/검증 완료 1구간 저장/)).toBeVisible({timeout:15000})
 await page.reload()
 await expect(status.getByText(/학생부 분석 진행 중/)).toBeVisible()
 await expect(page.getByRole('button',{name:'분석 취소',exact:true})).toBeVisible()
 await status.screenshot({path:testInfo.outputPath('recovery-running.png')})
 await status.getByRole('button',{name:'진행 중인 분석 취소',exact:true}).click()
 const resume=status.getByRole('button',{name:'저장 구간부터 이어서 분석',exact:true})
 await expect(resume).toBeEnabled({timeout:15000})
 await status.screenshot({path:testInfo.outputPath('recovery-ready.png')})
 await resume.click()
 await expect.poll(async()=>{const value=await(await request.get('/api/cases/'+target.id+'/jobs')).json();return value.jobs.at(-1)?.state},{timeout:15000}).toBe('succeeded')
 const calls=await(await request.get('/__synthetic_calls')).json()
 expect(calls.source_ids).toEqual(['s1','s2','s2'])
 expect(calls.synthesis).toBe(1)
 await expect(resume).toHaveCount(0)
 await expect(status.getByText('이 학생의 진행 중인 분석이 없습니다.')).toBeVisible()
 expect(errors).toEqual([])
})
